'use strict';
const express = require('express');
const { authMiddleware, requireRole } = require('../../middleware/auth');
const controller = require('./controller');
const router = express.Router();
router.get('/', authMiddleware, controller.list);
router.get('/:id/temperature-assessment', authMiddleware, controller.temperatureAssessment);
router.get('/:id', authMiddleware, controller.get);
router.post('/', authMiddleware, requireRole('farmer', 'admin', 'fisheries_manager'), controller.create);
router.put('/:id', authMiddleware, requireRole('farmer', 'admin', 'fisheries_manager'), controller.update);
router.delete('/:id', authMiddleware, requireRole('admin', 'fisheries_manager'), controller.remove);
module.exports = router;
