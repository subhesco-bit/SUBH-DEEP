#!/usr/bin/env node
/**
 * export-reference-seed.js — make the curated reference data reproducible.
 *
 * The database holds ~3,300 rows of hand-curated domain data: the NE variety
 * directory, HSN/GST mappings, nutrient tables, government schemes, the chart
 * of accounts, crop concept vocabularies. None of it is in the repository — it
 * exists only inside one Docker volume. Losing that volume loses the data, and
 * no migration can recreate it.
 *
 * This writes it back out as idempotent seed SQL so a fresh environment can be
 * provisioned from the repo alone.
 *
 * Operational tables (users, sessions, logs, migrations bookkeeping) are
 * excluded: they are per-environment state, not reference data.
 *
 * Usage:
 *   node tools/export-reference-seed.js
 *   node tools/export-reference-seed.js --out backend/src/database/seeds
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const arg = (n, d) => {
  const i = process.argv.indexOf(n);
  return i === -1 ? d : process.argv[i + 1];
};
const OUT_DIR = path.resolve(ROOT, arg('--out', 'backend/src/database/seeds'));
const CONTAINER = arg('--container', 'ebdesign-postgres');
const DB = arg('--db', 'ebdesign');
const USER = arg('--user', 'ebdesign_user');

/** Per-environment state, not reference data. */
const EXCLUDE = [
  /^migrations$/,
  /^users$/, /^user_profiles$/, /^user_.*preferences$/, /^user_sessions$/,
  /^sessions?$/, /^refresh_tokens$/,
  /_logs?$/, /^search_logs$/, /^audit/, /_audit$/,
  /^library_knowledge$/,          // regenerated by the library indexer
  /_cache$/, /^cache_/,
  /_metrics$/, /_stats$/,
];

const psql = (sql) => execFileSync(
  'docker',
  ['exec', CONTAINER, 'psql', '-U', USER, '-d', DB, '-tAc', sql],
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
).trim();

/**
 * Exact row counts for every table that has any.
 *
 * A first version raised NOTICEs from a DO block, which psql writes to stderr —
 * execFileSync returns stdout, so it read back nothing and reported 0 tables.
 * This builds one UNION ALL query instead, so the counts arrive as rows.
 * ANALYZE first so the reltuples prefilter is not working from stale stats.
 */
function tablesWithData() {
  psql('ANALYZE;');

  const names = psql(`
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
      AND c.reltuples <> 0
    ORDER BY c.relname;`)
    .split('\n').map((s) => s.trim()).filter(Boolean);

  if (!names.length) return [];

  // Exact counts, since reltuples is an estimate.
  const union = names
    .map((n) => `SELECT '${n}' AS t, count(*) AS c FROM "${n}"`)
    .join(' UNION ALL ');
  const rows = psql(`SELECT t || '|' || c FROM (${union}) q WHERE c > 0 ORDER BY c DESC;`);

  return rows
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => {
      const [name, count] = l.split('|');
      return { name, count: Number(count) };
    })
    .filter((t) => t.name && Number.isFinite(t.count) && t.count > 0);
}

const isExcluded = (n) => EXCLUDE.some((re) => re.test(n));

function dumpTable(name) {
  // --column-inserts gives explicit column names, so the seed survives a
  // later column reorder. --on-conflict-do-nothing makes it re-runnable.
  return execFileSync(
    'docker',
    ['exec', CONTAINER, 'pg_dump', '-U', USER, '-d', DB,
      '--data-only', '--column-inserts', '--on-conflict-do-nothing',
      '--no-owner', '--no-privileges', '-t', `public.${name}`],
    { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 },
  );
}

const all = tablesWithData();
const keep = all.filter((t) => !isExcluded(t.name)).sort((a, b) => b.count - a.count);
const skipped = all.filter((t) => isExcluded(t.name));

console.log('\n══════════ REFERENCE SEED EXPORT ══════════\n');
console.log(`  tables with data : ${all.length}`);
console.log(`  exporting        : ${keep.length}  (${keep.reduce((a, t) => a + t.count, 0)} rows)`);
console.log(`  skipped as state : ${skipped.length}  (${skipped.reduce((a, t) => a + t.count, 0)} rows)\n`);

fs.mkdirSync(OUT_DIR, { recursive: true });

const header = `-- Reference data seed — generated by tools/export-reference-seed.js
--
-- Curated domain data that no migration can recreate: the NE variety
-- directory, HSN/GST mappings, nutrient tables, government schemes, the chart
-- of accounts and the crop concept vocabularies. Before this file existed the
-- data lived only inside one Docker volume.
--
-- Idempotent: every statement is ON CONFLICT DO NOTHING, so re-running it
-- against a populated database is a no-op.
--
-- Foreign keys are deferred for the load. Tables are emitted largest-first,
-- not in dependency order, and several carry circular references
-- (chart_of_accounts, categories, resource_groups, companies) which no linear
-- ordering can satisfy. Without this the first run failed on
-- crop_concept_terms and only succeeded on a second pass, once its parent rows
-- happened to exist. session_replication_role = replica suspends FK and
-- trigger enforcement for this session only; the constraints themselves are
-- untouched and are enforced again as soon as it ends.
--
-- Regenerate with:  node tools/export-reference-seed.js
-- Generated:        ${new Date().toISOString()}

BEGIN;
SET session_replication_role = replica;

`;

const footer = `
SET session_replication_role = DEFAULT;
COMMIT;

-- Re-check every constraint now that the data is in. This fails loudly if the
-- seed is internally inconsistent, rather than leaving a quietly broken graph.
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT conrelid::regclass AS tbl, conname
    FROM pg_constraint
    WHERE contype = 'f' AND connamespace = 'public'::regnamespace
  LOOP
    BEGIN
      EXECUTE format('ALTER TABLE %s VALIDATE CONSTRAINT %I', r.tbl, r.conname);
    EXCEPTION WHEN others THEN
      RAISE WARNING 'seed: constraint % on % did not validate: %', r.conname, r.tbl, SQLERRM;
    END;
  END LOOP;
END $$;
`;

let body = '';
let exported = 0;
for (const t of keep) {
  try {
    const sql = dumpTable(t.name);
    const inserts = sql.split('\n').filter((l) => l.startsWith('INSERT INTO'));
    if (!inserts.length) continue;
    body += `\n-- ${t.name} (${t.count} rows)\n${inserts.join('\n')}\n`;
    exported += 1;
    process.stderr.write(`  ✓ ${t.name} (${t.count})\n`);
  } catch (e) {
    process.stderr.write(`  ✗ ${t.name}: ${String(e.message).split('\n')[0]}\n`);
  }
}

const outFile = path.join(OUT_DIR, '001_reference_data.sql');
fs.writeFileSync(outFile, header + body + footer);

console.log(`\n  wrote ${path.relative(ROOT, outFile)}`);
console.log(`  ${exported} tables, ${(fs.statSync(outFile).size / 1024).toFixed(0)} KB\n`);
console.log('  Skipped (per-environment state):');
for (const s of skipped) console.log(`    ${s.name} (${s.count})`);
console.log('');
